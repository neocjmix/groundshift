#!/usr/bin/env node
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const packages = [
  '@sparkjsdev/spark',
  'three',
  'react',
  'react-dom',
  'zod',
  'scheduler',
];

function sourceUrl(repository) {
  let reference = typeof repository === 'string' ? repository : repository?.url;
  if (typeof reference !== 'string') throw new Error('Package repository URL is missing');
  reference = reference.replace(/^git\+/, '').replace(/^github:/, 'https://github.com/');
  if (/^[\w.-]+\/[\w.-]+$/.test(reference)) reference = `https://github.com/${reference}`;
  reference = reference.replace(/\.git$/, '');
  const url = new URL(reference);
  if (url.protocol !== 'https:' || url.username || url.password) {
    throw new Error(`Unsupported package source URL: ${reference}`);
  }
  return url.href.replace(/\/$/, '');
}

async function packageNotice(name) {
  const directory = path.join(root, 'node_modules', name);
  const metadata = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
  if (metadata.name !== name || !metadata.version || metadata.license !== 'MIT') {
    throw new Error(`${name}: expected a versioned MIT package; review its license before distributing`);
  }
  const license = await readFile(path.join(directory, 'LICENSE'), 'utf8');
  if (!license.includes('Permission is hereby granted') || !license.includes('THE SOFTWARE IS PROVIDED')) {
    throw new Error(`${name}: LICENSE does not contain the expected complete MIT grant and disclaimer`);
  }
  const sourceDirectory = typeof metadata.repository === 'object' && metadata.repository.directory;
  const heading = [
    `${name} ${metadata.version}`,
    `Package: https://www.npmjs.com/package/${name}/v/${metadata.version}`,
    `Source: ${sourceUrl(metadata.repository)}`,
    ...(sourceDirectory ? [`Source directory: ${sourceDirectory}`] : []),
    `License: ${metadata.license}`,
  ].join('\n');
  // Keep the installed license text intact, including its copyright notices.
  return `${heading}\n\n${license}${license.endsWith('\n') ? '' : '\n'}`;
}

async function main() {
  if (process.argv.length > 2) throw new Error('Usage: node scripts/write-notices.mjs');
  const notices = await Promise.all(packages.map(packageNotice));
  const contents = [
    'Groundshift — Third-party runtime software notices',
    '',
    'Generated by scripts/write-notices.mjs from the installed runtime packages.',
    'The versions and complete license texts below describe this browser build.',
    'Scene datasets have separate attribution and licenses in their world folders.',
    '',
    notices.join(`\n${'='.repeat(72)}\n\n`),
  ].join('\n');
  const destination = path.join(root, 'public', 'THIRD_PARTY_NOTICES.txt');
  await mkdir(path.dirname(destination), { recursive: true });
  const temporary = `${destination}.${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, contents, { flag: 'wx' });
    await rename(temporary, destination);
  } finally {
    await rm(temporary, { force: true });
  }
  console.log(`Wrote ${packages.length} runtime package notices to public/THIRD_PARTY_NOTICES.txt`);
}

main().catch((error) => {
  console.error(`Third-party notices failed: ${error.message}. Run npm ci if dependencies are missing.`);
  process.exitCode = 1;
});
